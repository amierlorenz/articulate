"""Tests for Runs.md and Dashboard.md (Acceptance check 0.16)."""
from datetime import UTC, datetime
from pathlib import Path

import pytest

from articulate.core.dashboard import Dashboard
from articulate.core.db import Database
from articulate.core.runlog import RunLog
from articulate.core.vault import Vault


@pytest.fixture
def dash_env(tmp_path: Path):
    db_path = tmp_path / "test.sqlite3"
    db = Database(db_path)
    db.migrate()
    vault_dir = tmp_path / "vault"
    vault = Vault(vault_dir, db)
    runlog = RunLog(vault)
    dashboard = Dashboard(db, vault)
    return dashboard, vault, db, runlog


def test_runs_md_append_only(dash_env):
    _, vault, _, runlog = dash_env
    runlog.line("- 2026-11-20 02:00→02:41 nightly ✅ items 14 done · run 01JD")
    runlog.health_appeared("ollama_down", datetime(2026, 11, 20, 2, 41, tzinfo=UTC))
    runlog.health_recovered("ollama_down", datetime(2026, 11, 20, 10, 15, tzinfo=UTC))

    runs_file = vault.vault_dir / "_system" / "Runs.md"
    assert runs_file.exists()
    lines = runs_file.read_text(encoding="utf-8").strip().splitlines()
    assert len(lines) == 3
    assert "nightly ✅" in lines[0]
    assert "⚠️ appeared: ollama_down" in lines[1]
    assert "✅ recovered: ollama_down" in lines[2]


def test_dashboard_sections_in_order(dash_env):
    dashboard, _vault, db, _ = dash_env

    # Seed data
    with db.connect() as conn:
        # A crashed run (started with no end)
        conn.execute(
            "INSERT INTO runs (run_id, job, started_at, status) VALUES ('run-crashed', 'nightly', '2026-11-19T02:00:00Z', 'running');"
        )
        # A successful run
        conn.execute(
            "INSERT INTO runs (run_id, job, started_at, ended_at, status) VALUES ('run-succ', 'pass2', '2026-11-20T03:05:00Z', '2026-11-20T03:15:00Z', 'ok');"
        )
        conn.commit()

    now = datetime(2026, 11, 20, 12, 0, tzinfo=UTC)
    rendered = dashboard.render(now=now)

    # Check frontmatter
    assert "agent: true" in rendered
    assert "generated: true" in rendered
    assert "Regenerated by Articulate, don't edit." in rendered

    # Check sections in order (§3.11)
    s1 = rendered.find("## Status")
    s2 = rendered.find("## Jobs")
    s3 = rendered.find("## Model Budget Today")
    s4 = rendered.find("## Items Held")
    s5 = rendered.find("## Encore Hand-off")
    s6 = rendered.find("## Dependencies")

    assert s1 != -1
    assert s2 != -1
    assert s3 != -1
    assert s4 != -1
    assert s5 != -1
    assert s6 != -1
    assert s1 < s2 < s3 < s4 < s5 < s6

    # Crashed run check: the nightly run with no ended_at should show "crashed"
    jobs_part = rendered[s2:s3]
    assert "crashed" in jobs_part.lower()


def test_dashboard_write_only_when_hash_changed(dash_env):
    dashboard, vault, _, _ = dash_env
    dash_file = vault.vault_dir / "_system" / "Dashboard.md"
    now = datetime(2026, 11, 20, 12, 0, tzinfo=UTC)

    # First write
    wrote1 = dashboard.write(now=now)
    assert wrote1 is True
    assert dash_file.exists()
    mtime1 = dash_file.stat().st_mtime_ns

    # Second write with same state -> skipped
    wrote2 = dashboard.write(now=now)
    assert wrote2 is False
    mtime2 = dash_file.stat().st_mtime_ns
    assert mtime1 == mtime2
