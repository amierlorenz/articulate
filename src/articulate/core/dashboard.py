"""Generated dashboard snapshot _system/Dashboard.md (§3.11, Issue #45)."""
from datetime import UTC, datetime

from articulate.core.db import Database
from articulate.core.vault import Vault


class Dashboard:
    """Renders and writes _system/Dashboard.md snapshot (§3.11)."""

    def __init__(self, db: Database, vault: Vault):
        self.db = db
        self.vault = vault

    def render(self, now: datetime | None = None) -> str:
        """Render markdown text for Dashboard.md with sections in strict order (§3.11)."""
        dt = now or datetime.now(UTC)
        lines: list[str] = [
            "---",
            "agent: true",
            "generated: true",
            "---",
            "Regenerated by Articulate, don't edit.",
            "",
            "# Dashboard",
            "",
        ]

        # Section 1: Status
        lines.append("## Status")
        with self.db.connect() as conn:
            problems = conn.execute(
                """
                SELECT kind, key, detail, first_seen, last_seen, interrupt
                FROM health
                WHERE recovered_at IS NULL
                ORDER BY first_seen DESC;
                """
            ).fetchall()

        if not problems:
            lines.append("✅ all good")
        else:
            lines.append(f"⚠️ {len(problems)} problems")
            lines.append("")
            lines.append("| Kind | Key | First Seen | Detail | Status |")
            lines.append("|---|---|---|---|---|")
            for p in problems:
                k = p["kind"]
                key = p["key"] or "—"
                fs = p["first_seen"]
                det = (p["detail"] or "").replace("\n", " ")
                status = "interrupting" if p["interrupt"] == 1 else "active"
                lines.append(f"| {k} | {key} | {fs} | {det} | {status} |")
        lines.append("")

        # Section 2: Jobs
        lines.append("## Jobs")
        lines.append("| Job | Last Start | Last Success | Lateness | Streak | Status |")
        lines.append("|---|---|---|---|---|---|")

        job_names = ["nightly", "pass2", "watch", "Encore import"]
        for j in job_names:
            last_start = "—"
            last_succ = "—"
            lateness = "ok"
            streak = 0
            job_status = "ok"

            if j != "Encore import":
                with self.db.connect() as conn:
                    latest = conn.execute(
                        "SELECT * FROM runs WHERE job = ? ORDER BY started_at DESC LIMIT 1;",
                        (j,),
                    ).fetchone()
                    succ = conn.execute(
                        "SELECT * FROM runs WHERE job = ? AND status = 'ok' ORDER BY ended_at DESC LIMIT 1;",
                        (j,),
                    ).fetchone()
                    recent = conn.execute(
                        "SELECT status FROM runs WHERE job = ? ORDER BY started_at DESC LIMIT 10;",
                        (j,),
                    ).fetchall()

                if latest:
                    last_start = latest["started_at"]
                    # Check for crashed run (start with no end)
                    if latest["ended_at"] is None and latest["status"] != "ok":
                        job_status = "crashed"
                    elif latest["status"] == "failed":
                        job_status = "failed"
                    else:
                        job_status = "ok"

                if succ:
                    last_succ = succ["ended_at"]
                    # Compute lateness / staleness
                    try:
                        succ_dt = datetime.fromisoformat(succ["ended_at"])
                        diff_hours = (dt - succ_dt).total_seconds() / 3600.0
                        if (diff_hours > 26.0 and j in ("nightly", "pass2")) or (
                            diff_hours > 2.0 and j == "watch"
                        ):
                            lateness = f"stale ({diff_hours:.1f}h)"
                    except Exception:  # noqa: BLE001, S110
                        pass
                elif latest:
                    lateness = "stale (no success)"

                # Compute failure streak
                for r in recent:
                    if r["status"] == "ok":
                        break
                    streak += 1
            else:
                # Encore import
                with self.db.connect() as conn:
                    snap = conn.execute(
                        "SELECT exported_at FROM encore_snapshots WHERE schema = 'encore.state' ORDER BY exported_at DESC LIMIT 1;"
                    ).fetchone()
                if snap:
                    last_succ = snap["exported_at"]
                    last_start = snap["exported_at"]
                    try:
                        exp_dt = datetime.fromisoformat(snap["exported_at"])
                        diff_days = (dt - exp_dt).total_seconds() / 86400.0
                        if diff_days > 2.0:
                            lateness = f"stale ({diff_days:.1f}d)"
                    except Exception:  # noqa: BLE001, S110
                        pass

            lines.append(f"| {j} | {last_start} | {last_succ} | {lateness} | {streak} | {job_status} |")
        lines.append("")

        # Section 3: Model Budget Today
        lines.append("## Model Budget Today")
        lines.append("| Provider | Model | Today Calls | Limit / RPD | Notes |")
        lines.append("|---|---|---|---|---|")

        today_str = dt.strftime("%Y-%m-%d")
        with self.db.connect() as conn:
            model_rows = conn.execute(
                """
                SELECT provider, model, COUNT(*) as cnt
                FROM model_calls
                WHERE pacific_date = ? OR started_at LIKE ?
                GROUP BY provider, model;
                """,
                (today_str, f"{today_str}%"),
            ).fetchall()

            claude_row = conn.execute(
                "SELECT * FROM claude_usage ORDER BY checked_at DESC LIMIT 1;"
            ).fetchone()

        if model_rows:
            for mr in model_rows:
                lines.append(f"| {mr['provider']} | {mr['model']} | {mr['cnt']} | — | — |")
        else:
            lines.append("| gemini | gemini-3.8-flash | 0 | 1500 | — |")
            lines.append("| gemini | gemini-3.5-flash-lite | 0 | 1500 | — |")

        if claude_row:
            sess_pct = f"{claude_row['session_pct']}%" if claude_row["session_pct"] is not None else "—"
            week_pct = f"{claude_row['weekly_pct']}%" if claude_row["weekly_pct"] is not None else "—"
            exp_at = claude_row["credential_expires_at"] or "—"
            lines.append(f"| anthropic | claude-3-7-sonnet | session: {sess_pct} | weekly: {week_pct} | expires: {exp_at} |")
        lines.append("")

        # Section 4: Items Held
        lines.append("## Items Held")
        with self.db.connect() as conn:
            held_rows = conn.execute(
                """
                SELECT hold_reason, COUNT(*) as cnt
                FROM items
                WHERE status = 'held'
                GROUP BY hold_reason;
                """
            ).fetchall()

            open_flags_row = conn.execute(
                "SELECT COUNT(*) as cnt FROM flags WHERE status = 'open';"
            ).fetchone()
            open_flags_count = open_flags_row["cnt"] if open_flags_row else 0

        lines.append(f"Open intake flags: [{open_flags_count} open flags](Inbox/Intake%20flags.md)")
        lines.append("")
        lines.append("| Hold Reason | Count |")
        lines.append("|---|---|")
        if held_rows:
            for hr in held_rows:
                lines.append(f"| {hr['hold_reason'] or 'unspecified'} | {hr['cnt']} |")
        else:
            lines.append("| none | 0 |")
        lines.append("")

        # Section 5: Encore Hand-off
        lines.append("## Encore Hand-off")
        lines.append("| Metric | Value |")
        lines.append("|---|---|")

        with self.db.connect() as conn:
            snap_row = conn.execute(
                "SELECT exported_at FROM encore_snapshots WHERE schema = 'encore.state' ORDER BY exported_at DESC LIMIT 1;"
            ).fetchone()
            ack_row = conn.execute(
                "SELECT file_id, acked_at FROM handoff_files WHERE acked_at IS NOT NULL ORDER BY acked_at DESC LIMIT 1;"
            ).fetchone()

        last_state = snap_row["exported_at"] if snap_row else "—"
        last_batch = f"{ack_row['file_id']} ({ack_row['acked_at']})" if ack_row else "—"
        lines.append(f"| Last state.json exportedAt | {last_state} |")
        lines.append(f"| Last acknowledged batch | {last_batch} |")
        lines.append("| plan.json age | — |")
        lines.append("")

        # Section 6: Dependencies
        lines.append("## Dependencies")
        lines.append("| Dependency | Status | Notes |")
        lines.append("|---|---|---|")
        lines.append("| Ollama | unknown | local daemon |")
        lines.append("| DeckCraft / Keynote | unknown | PPTX converter |")
        lines.append("| Canvas token | unknown | keychain item |")
        lines.append("| Pocket API | unknown | keychain item |")
        lines.append("| Google token | unknown | keychain item |")
        lines.append("")

        return "\n".join(lines)

    def write(self, now: datetime | None = None) -> bool:
        """Render and write Dashboard.md through vault.write_system (§3.11)."""
        content = self.render(now)
        return self.vault.write_system("Dashboard.md", content)


def write_dashboard(db: Database, vault: Vault, now: datetime | None = None) -> bool:
    """Helper to render and write Dashboard.md (§3.11)."""
    d = Dashboard(db, vault)
    return d.write(now)
